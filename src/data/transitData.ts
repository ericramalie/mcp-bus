// Fallback generator for other stops
export function getArrivalsForStop(stopCode: string): BusArrivalService[] {
  if (MOCK_BUS_ARRIVALS[stopCode]) {
    return MOCK_BUS_ARRIVALS[stopCode];
  }
  const stop = BUS_STOPS.find(s => s.code === stopCode);
  if (!stop) return [];

  // Generate realistic arrivals based on stop's listed services
  return stop.services.slice(0, 4).map((svcNo, idx) => {
    const isExpress = svcNo.startsWith('5');
    const firstSecs = 15 + idx * 110;
    const firstStr = firstSecs <= 45 ? 'Arr' : `${Math.ceil(firstSecs / 60)} mins`;
    const sec2 = firstSecs + 380 + (idx * 60);
    const sec3 = sec2 + 450 + (idx * 80);

    return {
      serviceNo: svcNo,
      category: isExpress ? 'express' : 'trunk',
      operator: 'SBS Transit',
      destinationName: 'Interchange Terminal',
      destinationCode: '00000',
      originName: stop.name,
      firstBus: '05:30',
      lastBus: '23:45',
      frequency: '6 - 10 mins',
      routeStopsCount: 45,
      nextBuses: [
        {
          arrivalTime: firstStr,
          secondsLeft: firstSecs,
          crowding: idx === 0 ? 'seats-available' : idx === 1 ? 'standing-available' : 'seats-available',
          type: idx % 2 === 0 ? 'DD' : 'SD',
          wheelchairAccessible: true,
          busPlate: `SBS${3000 + idx * 142}M`,
        },
        {
          arrivalTime: `${Math.ceil(sec2 / 60)} mins`,
          secondsLeft: sec2,
          crowding: 'seats-available',
          type: 'DD',
          wheelchairAccessible: true,
          busPlate: `SBS${3100 + idx * 142}T`,
        },
        {
          arrivalTime: `${Math.ceil(sec3 / 60)} mins`,
          secondsLeft: sec3,
          crowding: idx === 2 ? 'limited-standing' : 'standing-available',
          type: 'DD',
          wheelchairAccessible: true,
          busPlate: `SBS${3200 + idx * 142}X`,
        },
      ],
    };
  });
}

